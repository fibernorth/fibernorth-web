export interface PricingSettings {
  rules: PricingRules;
  items: PriceItem[];
  updatedAt?: string;
  updatedBy?: string;
}

export const DEFAULT_PRICING: PricingSettings = { rules: DEFAULT_PRICING_RULES, items: DEFAULT_PRICE_LIST };

/** Keys of quote lines generated by the rules all start with this. */
export const RULE_KEY_PREFIX = "rules:";
export const isRuleKey = (key: string | undefined): boolean => !!key && key.startsWith(RULE_KEY_PREFIX);

export interface RuleInput {
  people: number;
  days: number;
  lines: Array<{ feet: number }>;
}

export interface RuleItem {
  /** Stable quote-line key: "rules:crew" or "rules:line:<index of the line>". */
  key: string;
  description: string;
  amount: number;
}

export interface RuleResult {
  /** The labor price: the higher of byCrew and byFootage. */
  labor: number;
  method: "crew" | "footage";
  byCrew: { total: number; items: RuleItem[] };
  byFootage: { total: number; items: RuleItem[] };
  /** The winning method's items, which become the auto labor lines. */
  items: RuleItem[];
  manDays: number;
  /** labor ÷ man-days (null with no crew). */
  laborPerManDay: number | null;
}

const fmt = (n: number): string =>
  n.toLocaleString("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: Number.isInteger(n) ? 0 : 2,
    maximumFractionDigits: 2,
  });
const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;
const round2 = (n: number) => Math.round(n * 100) / 100;
const num = (n: unknown): number => (typeof n === "number" && Number.isFinite(n) && n > 0 ? n : 0);

/** One line's own price and wording under the footage tiers. */
export function linePrice(feetIn: number, r: PricingRules): { amount: number; description: string; short: boolean } {
  const feet = Math.round(num(feetIn));
  if (feet <= r.shortMaxFeet) {
    return { amount: r.extraShortLine, description: `Extra line ≤${r.shortMaxFeet} ft (${feet} ft)`, short: true };
  }
  if (feet <= r.midMaxFeet) {
    return { amount: r.midPrice, description: `Line ${feet} ft (${r.shortMaxFeet}–${r.midMaxFeet} ft)`, short: false };
  }
  if (feet <= r.longMaxFeet) {
    return { amount: r.longPrice, description: `Line ${feet} ft (${r.midMaxFeet}–${r.longMaxFeet} ft)`, short: false };
  }
  // Never less than the 200–300 ft price, so a 301 ft line doesn't dip under a 300 ft one.
  const perFoot = round2(feet * r.perFootOver);
  if (perFoot < r.longPrice) {
    return { amount: r.longPrice, description: `Line ${feet} ft (over ${r.longMaxFeet} ft, ${fmt(r.longPrice)} minimum)`, short: false };
  }
  return { amount: perFoot, description: `Line ${feet} ft × ${fmt(r.perFootOver)}/ft`, short: false };
}

export function quoteRules(input: RuleInput, r: PricingRules = DEFAULT_PRICING_RULES): RuleResult {
  const people = num(input.people);
  const days = num(input.days);
  const manDays = people * days;
  const lines = (input.lines || []).map((l, i) => ({ i, feet: Math.round(num(l.feet)) })).filter((l) => l.feet > 0);

  // By crew: the day covers one short line; each further short line adds on.
  const crewItems: RuleItem[] = [];
  const crewBase = round2(manDays * r.perPersonDay);
  crewItems.push({
    key: `${RULE_KEY_PREFIX}crew`,
    description: `Crew: ${people} ${people === 1 ? "person" : "people"} × ${plural(days, "day")} × ${fmt(r.perPersonDay)}`,
    amount: crewBase,
  });
  let firstShortSeen = false;
  for (const l of lines) {
    if (l.feet > r.shortMaxFeet) continue;
    if (!firstShortSeen) {
      firstShortSeen = true;
      continue;
    }
    crewItems.push({ key: `${RULE_KEY_PREFIX}line:${l.i}`, description: `Extra line ≤${r.shortMaxFeet} ft (${l.feet} ft)`, amount: r.extraShortLine });
  }

  // By footage: every line at its own price.
  const footageItems: RuleItem[] = lines.map((l) => {
    const p = linePrice(l.feet, r);
    return { key: `${RULE_KEY_PREFIX}line:${l.i}`, description: p.description, amount: p.amount };
  });

  const sum = (items: RuleItem[]) => round2(items.reduce((s, it) => s + it.amount, 0));
  const crewTotal = sum(crewItems);
  const footageTotal = sum(footageItems);
  const method = footageTotal > crewTotal ? "footage" : "crew";
  const labor = method === "crew" ? crewTotal : footageTotal;
  return {
    labor,
    method,
    byCrew: { total: crewTotal, items: crewItems },
    byFootage: { total: footageTotal, items: footageItems },
    items: method === "crew" ? crewItems : footageItems,
    manDays,
    laborPerManDay: manDays > 0 ? round2(labor / manDays) : null,
  };
}

/**
 * Why a quote's actual labor needs the owner's OK, or "" when it's fine.
 * Actual labor = the quote's work lines (materials never count).
 */
export function belowRules(actualLabor: number, result: RuleResult, r: PricingRules = DEFAULT_PRICING_RULES): string {
  const actual = round2(Math.max(0, Number(actualLabor) || 0));
  const reasons: string[] = [];
  if (actual < result.labor - 0.005) {
    reasons.push(`Below the price rules: ${fmt(round2(result.labor - actual))} less than ${fmt(result.labor)}`);
  }
  if (result.manDays > 0 && actual / result.manDays < r.minPerManDay - 0.005) {
    reasons.push(`Under ${fmt(r.minPerManDay)} per man-day (${fmt(round2(actual / result.manDays))})`);
  }
  return reasons.join("; ");
}

/**
 * Put freshly computed rule lines into a quote's lines. Auto rule lines are
 * replaced; a rule line the estimator edited (source "manual") is kept and
 * its auto twin left out. With `reset`, every rule line (edited or not) and
 * the old rate-sheet bore lines ("drawing:bore", "rate-sheet:bore") are
 * replaced. New lines go where the old rule lines were, or first.
 */
export function mergeRuleLines<T extends { key?: string; source?: "auto" | "manual" }>(
  current: T[],
  fresh: T[],
  opts: { reset?: boolean } = {}
): T[] {
  const legacy = (k?: string) => k === "drawing:bore" || k === "rate-sheet:bore";
  const replaced = (l: T) =>
    opts.reset ? isRuleKey(l.key) || legacy(l.key) : isRuleKey(l.key) && l.source !== "manual";
  const firstAt = current.findIndex(replaced);
  const kept = current.filter((l) => !replaced(l));
  const held = new Set(kept.map((l) => l.key).filter(isRuleKey));
  const add = fresh.filter((l) => !held.has(l.key));
  const at = firstAt < 0 ? 0 : current.slice(0, firstAt).filter((l) => !replaced(l)).length;
  return [...kept.slice(0, at), ...add, ...kept.slice(at)];
}

/** Clamp and fill an owner's settings doc (anything missing or bad → default). */
export function cleanPricing(raw: unknown): PricingSettings {
  const src = (raw && typeof raw === "object" ? raw : {}) as Record<string, unknown>;
  const rr = (src.rules && typeof src.rules === "object" ? src.rules : {}) as Record<string, unknown>;
  const rules = { ...DEFAULT_PRICING_RULES };
  (Object.keys(DEFAULT_PRICING_RULES) as Array<keyof PricingRules>).forEach((k) => {
    const v = Number(rr[k]);
    if (rr[k] !== undefined && rr[k] !== null && rr[k] !== "" && Number.isFinite(v) && v >= 0 && v <= 1_000_000) {
      rules[k] = round2(v);
    }
  });
  let items = DEFAULT_PRICE_LIST;
  if (Array.isArray(src.items)) {
    const seen = new Set<string>();
    items = src.items
      .slice(0, 300)
      .map((x, i): PriceItem | null => {
        const it = (x && typeof x === "object" ? x : {}) as Record<string, unknown>;
        const name = String(it.name ?? "").trim().slice(0, 120);
        if (!name) return null;
        let id = String(it.id ?? "").trim().replace(/[^\w.-]/g, "").slice(0, 40) || `item-${i}`;
        while (seen.has(id)) id = `${id}-${i}`;
        seen.add(id);
        const p = it.price === null || it.price === undefined || it.price === "" ? null : Number(it.price);
        const qbo = String(it.qboItem ?? "").trim().slice(0, 100);
        return {
          id,
          name,
          kind: it.kind === "material" ? "material" : "work",
          unit: PRICE_UNITS.includes(it.unit as PriceUnit) ? (it.unit as PriceUnit) : "each",
          price: p !== null && Number.isFinite(p) && p >= 0 && p <= 1_000_000 ? round2(p) : null,
          ...(qbo ? { qboItem: qbo } : {}),
          active: it.active !== false,
        };
      })
      .filter((x): x is PriceItem => x !== null);
  }
  return {
    rules,
    items,
    ...(typeof src.updatedAt === "string" ? { updatedAt: src.updatedAt } : {}),
    ...(typeof src.updatedBy === "string" ? { updatedBy: src.updatedBy } : {}),
  };
}

/**
 * The approval reason for a quote as saved: its work lines (or, with no
 * lines, its typed price) checked against the rules. "" with no price at all.
 */
export function approvalReasonFor(
  q: { quoteLines?: Array<{ kind: string; qty: number; unitPrice: number }> | null; quotedPrice?: number | null },
  crew: RuleInput,
  r: PricingRules = DEFAULT_PRICING_RULES
): string {
  const lines = q.quoteLines ?? [];
  let labor: number;
  if (lines.length) {
    labor = lines.reduce((s, l) => (l.kind === "material" ? s : s + (Number(l.qty) || 0) * (Number(l.unitPrice) || 0)), 0);
  } else if (typeof q.quotedPrice === "number") {
    labor = q.quotedPrice;
  } else {
    return "";
  }
  return belowRules(labor, quoteRules(crew, r), r);
}

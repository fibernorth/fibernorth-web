// Bill's price rules for directional boring labor (Oct 2026). Pure.
//
// A quote starts from the crew: people × days. Two prices are worked out and
// the HIGHER one is the labor price:
//
//   By crew    = people × days × $1,500
//                + $1,000 for every line ≤150 ft after the first
//                (the crew's day covers one line up to 150 ft)
//
//   By footage = the sum of each line's own price:
//                  ≤150 ft          $1,000  (an extra short line)
//                  150–200 ft       $3,500
//                  200–300 ft       $4,000
//                  over 300 ft      feet × $13
//
// Examples (2 people, 1 day unless noted):
//   one 120 ft line        crew 3,000 vs footage 1,000  → $3,000
//   two lines ≤150 ft      crew 4,000 vs footage 2,000  → $4,000
//   one 250 ft line        crew 3,000 vs footage 4,000  → $4,000
//   250 ft + 100 ft        crew 3,000 vs footage 5,000  → $5,000
//   3 people, 2 days, short line   crew 9,000           → $9,000
//
// Boundaries: a line of exactly 150 ft is short, exactly 200 ft is 150–200,
// exactly 300 ft is 200–300. Feet are rounded to whole feet first.
// Floor: labor ÷ (people × days) must be at least $1,250 per man-day.
// Materials are separate lines and never count toward labor.
//
// Every number is editable by the owner on /admin/pricing (stored in
// Firestore pricingSettings/current, see src/services/pricing.ts).

export interface PricingRules {
  /** Crew price per person per day. */
  perPersonDay: number;
  /** One line up to this many feet is covered by the crew's day. */
  shortMaxFeet: number;
  /** Each extra line up to shortMaxFeet. */
  extraShortLine: number;
  /** Over shortMaxFeet up to midMaxFeet. */
  midMaxFeet: number;
  midPrice: number;
  /** Over midMaxFeet up to longMaxFeet. */
  longMaxFeet: number;
  longPrice: number;
  /** Over longMaxFeet: price per foot. */
  perFootOver: number;
  /** Lowest labor per man-day before a quote needs approval. */
  minPerManDay: number;
  /** What the quote builder starts with. */
  defaultPeople: number;
  defaultDays: number;
}

export const DEFAULT_PRICING_RULES: PricingRules = {
  perPersonDay: 1500,
  shortMaxFeet: 150,
  extraShortLine: 1000,
  midMaxFeet: 200,
  midPrice: 3500,
  longMaxFeet: 300,
  longPrice: 4000,
  perFootOver: 13,
  minPerManDay: 1250,
  defaultPeople: 2,
  defaultDays: 1,
};

export type PriceUnit = "ft" | "each" | "hour" | "day" | "lump";
export const PRICE_UNITS: PriceUnit[] = ["ft", "each", "hour", "day", "lump"];

/** One entry on the owner's price list. A null price is filled in on each quote. */
